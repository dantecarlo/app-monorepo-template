import { spawnSync } from 'node:child_process'
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterAll, describe, expect, test } from 'vitest'

import * as tokens from '@/tokens.constant'

import { OUTPUTS, renderOutputs } from '../generate.mjs'

// The package root, which holds the generator and the token source.
const PACKAGE_DIR = join(import.meta.dirname, '..', '..')
const GENERATOR = join(PACKAGE_DIR, 'scripts', 'generate.mjs')
const SOURCE = join('src', 'tokens.constant.ts')

const scratchDirs: string[] = []

afterAll(() => {
  scratchDirs.forEach((dir) =>
    rmSync(dir, { force: true, recursive: true })
  )
})

const kebab = (key: string) =>
  key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)

type LeafType = [string[], string]

const leaves = (value: unknown, path: string[] = []): LeafType[] =>
  value !== null && typeof value === 'object'
    ? Object.entries(value).flatMap(([key, child]) =>
        leaves(child, [...path, key])
      )
    : [[path, String(value)]]

const nameOf = (path: string[]) => path.map(kebab).join('-')

const contentOf = ({
  outputs,
  path
}: {
  outputs: { content: string; path: string }[]
  path: string
}) => outputs.find((output) => output.path === path)?.content ?? ''

const webTheme = (source: typeof tokens = tokens) =>
  contentOf({
    outputs: renderOutputs({ tokens: source }),
    path: OUTPUTS.webTheme
  })

// The body of the first block that opens with `opener`, brace-balanced.
const blockBody = ({ css, opener }: { css: string; opener: string }) => {
  const start = css.indexOf(opener)
  if (start === -1) return ''
  const open = css.indexOf('{', start)
  let depth = 0
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === '{') depth += 1
    if (css[i] === '}') depth -= 1
    if (depth === 0) return css.slice(open + 1, i)
  }
  return ''
}

const declarations = (body: string) =>
  Object.fromEntries(
    [...body.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(
      ([, name, value]) => [name, value.trim()]
    )
  )

const blocks = (css: string) => ({
  dark: declarations(
    blockBody({ css, opener: ":root,\n[data-theme='dark'] {" })
  ),
  inline: declarations(blockBody({ css, opener: '@theme inline {' })),
  light: declarations(
    blockBody({ css, opener: "[data-theme='light'] {" })
  ),
  theme: declarations(blockBody({ css, opener: '@theme {' }))
})

const isShared = (path: string[]) =>
  path.length === 1 && Object.hasOwn(tokens.sharedColors, path[0])

const themedLeaves = (theme: keyof typeof tokens.themes) =>
  leaves(tokens.themes[theme]).filter(([path]) => !isShared(path))

const runGenerator = (packageDir: string) =>
  spawnSync(process.execPath, [GENERATOR, '--package-dir', packageDir], {
    encoding: 'utf8'
  })

describe('token generator', () => {
  test('writes every output under its do-not-edit header, and rewrites nothing on a second run', () => {
    const packageDir = mkdtempSync(join(tmpdir(), 'tokens-generate-'))
    scratchDirs.push(packageDir)
    mkdirSync(join(packageDir, 'src'))
    copyFileSync(join(PACKAGE_DIR, SOURCE), join(packageDir, SOURCE))

    const first = runGenerator(packageDir)
    expect(first.status, first.stderr).toBe(0)
    expect(first.stdout).toContain('3 written')

    const expected = renderOutputs({ tokens })
    expect(expected.map(({ path }) => path).sort()).toEqual(
      Object.values(OUTPUTS).sort()
    )
    const written = expected.map(({ content, path }) => {
      const file = join(packageDir, path)
      expect(readFileSync(file, 'utf8')).toBe(content)
      expect(content).toMatch(
        /^(\/\*|\/\/) Generated by packages\/tokens\/scripts\/generate\.mjs from\n/
      )
      expect(content.split('\n').slice(0, 4).join(' ')).toMatch(
        /Do not edit this file/
      )
      return { file, modified: statSync(file).mtimeMs }
    })

    const second = runGenerator(packageDir)
    expect(second.status, second.stderr).toBe(0)
    expect(second.stdout).toContain('0 written')
    written.forEach(({ file, modified }) => {
      expect(statSync(file).mtimeMs).toBe(modified)
    })
  })

  test('a token added to the source reaches every output that carries its group', () => {
    const source = {
      ...tokens,
      spacing: { ...tokens.spacing, '4xl': 40 }
    } as unknown as typeof tokens
    const outputs = renderOutputs({ tokens: source })
    const shipped = renderOutputs({ tokens })

    expect(blocks(webTheme(source)).inline['spacing-4xl']).toBe('40px')
    expect(
      contentOf({ outputs, path: OUTPUTS.nativewindPreset })
    ).toContain("'4xl': '40px'")
    expect(contentOf({ outputs, path: OUTPUTS.themeVars })).toBe(
      contentOf({ outputs: shipped, path: OUTPUTS.themeVars })
    )
  })

  test('declares every themed colour in both theme blocks and maps it in @theme', () => {
    const { dark, light, theme } = blocks(webTheme())
    const darkLeaves = themedLeaves('dark')

    expect(Object.keys(dark).sort()).toEqual(
      darkLeaves.map(([path]) => `c-${nameOf(path)}`).sort()
    )
    darkLeaves.forEach(([path, value]) => {
      expect(dark[`c-${nameOf(path)}`]).toBe(value)
      expect(theme[`color-${nameOf(path)}`]).toBe(
        `var(--c-${nameOf(path)})`
      )
    })
    expect(Object.keys(light).sort()).toEqual(Object.keys(dark).sort())
    themedLeaves('light').forEach(([path, value]) => {
      expect(light[`c-${nameOf(path)}`]).toBe(value)
    })
  })

  test('writes every shared colour once, as a literal in @theme', () => {
    const { dark, light, theme } = blocks(webTheme())

    Object.entries(tokens.sharedColors).forEach(([key, value]) => {
      expect(theme[`color-${kebab(key)}`]).toBe(value)
      expect(dark).not.toHaveProperty(`c-${kebab(key)}`)
      expect(light).not.toHaveProperty(`c-${kebab(key)}`)
    })
  })

  test('inlines every scale in @theme inline as a CSS length', () => {
    const scale = ({
      format,
      prefix,
      values
    }: {
      format: (value: number) => string
      prefix: string
      values: Record<string, number>
    }) =>
      Object.entries(values).map(([key, value]) => [
        `${prefix}-${kebab(key)}`,
        format(value)
      ])
    const px = (value: number) => `${value}px`
    const rem = (value: number) => `${value}rem`

    expect(blocks(webTheme()).inline).toEqual(
      Object.fromEntries([
        ...scale({
          format: px,
          prefix: 'spacing',
          values: tokens.spacing
        }),
        ...scale({ format: px, prefix: 'spacing', values: tokens.inset }),
        ...scale({
          format: rem,
          prefix: 'container',
          values: tokens.layoutWidth
        }),
        ...scale({ format: px, prefix: 'radius', values: tokens.radius }),
        ...Object.entries(tokens.fontSize).flatMap(
          ([key, { lineHeight, size }]) => [
            [`text-${kebab(key)}`, px(size)],
            [`text-${kebab(key)}--line-height`, px(lineHeight)]
          ]
        ),
        ...scale({ format: px, prefix: 'text', values: tokens.glyphSize })
      ])
    )
  })

  test('writes each font stack with its loader variable and fallback, and the shimmer motion', () => {
    const { theme } = blocks(webTheme())

    expect(theme['font-body']).toBe('var(--font-inter), Inter, sans-serif')
    expect(theme['font-display']).toBe(
      'var(--font-montserrat), Montserrat, sans-serif'
    )
    expect(theme['duration-shimmer']).toBe('1600ms')
    expect(theme['ease-shimmer']).toBe('linear')
  })

  test('writes every shadow in @theme', () => {
    const { theme } = blocks(webTheme())

    Object.entries(tokens.shadows).forEach(([key, value]) => {
      expect(theme[`shadow-${kebab(key)}`]).toBe(value)
    })
  })
})
