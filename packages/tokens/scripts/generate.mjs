// ---------------------------------------------------------------------------
// generate — writes every token output from src/tokens.constant.ts.
//
// Decision 59: one source and one generator. Each output below has exactly
// one writer, this file, and starts with a header that says so;
// `pnpm verify:theme-sync` renders them again in memory and fails on any
// difference with the committed bytes.
//
//   theme.css                  the web theme: the --c-* variables of both
//                              themes, @theme and @theme inline
//   tailwind-preset.cjs        the NativeWind preset: each themed colour as
//                              its --c-* variable, each shared one as a
//                              literal, and the scales
//   src/themeVars.constant.ts  the mobile theme variables, per theme
//   src/themeNames.constant.ts the name of every token utility the web
//                              theme declares, per Tailwind namespace,
//                              which the web's tailwind-merge reads
//
// A token's output name is its key path in kebab case: themes.dark.bg.base
// is bg-base, accentSurface is accent-surface, fontSize.amountHero is
// amount-hero. A colour of sharedColors is theme-invariant and written once;
// every other colour is themed. A new consumer is one more render function
// in OUTPUTS and RENDERERS, and nothing else changes.
//
// Usage:
//   pnpm --filter @app/tokens generate
//   node scripts/generate.mjs [--package-dir <dir>]
// ---------------------------------------------------------------------------

import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync
} from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')

export const GENERATE_COMMAND = 'pnpm --filter @app/tokens generate'
export const SOURCE = 'src/tokens.constant.ts'

export const OUTPUTS = Object.freeze({
  nativewindPreset: 'tailwind-preset.cjs',
  themeNames: 'src/themeNames.constant.ts',
  themeVars: 'src/themeVars.constant.ts',
  webTheme: 'theme.css'
})

const HEADER = [
  'Generated by packages/tokens/scripts/generate.mjs from',
  'packages/tokens/src/tokens.constant.ts. Do not edit this file: change the',
  `source, then run \`${GENERATE_COMMAND}\`.`,
  '`pnpm verify:theme-sync` fails while it differs from its regeneration.'
]

// The token module, read synchronously: Node strips the TypeScript types,
// so the gate can regenerate inside a synchronous run.
export const loadTokens = ({ packageDir }) =>
  createRequire(import.meta.url)(join(packageDir, SOURCE))

// ---------------------------------------------------------------------------
// Naming and values
// ---------------------------------------------------------------------------

const kebab = (key) =>
  key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)

const nameOf = (path) => path.map(kebab).join('-')

// Every [path, value] leaf of a nested object, in key order.
const leaves = (value, path = []) =>
  value !== null && typeof value === 'object'
    ? Object.entries(value).flatMap(([key, child]) =>
        leaves(child, [...path, key])
      )
    : [[path, value]]

const px = (value) => `${value}px`
const rem = (value) => `${value}rem`
const ms = (value) => `${value}ms`

// Code-point order, the same on every runtime and locale.
const compare = (left, right) => (left < right ? -1 : left > right ? 1 : 0)

const byName = (left, right) => compare(left.name, right.name)

const isShared = ({ path, tokens }) =>
  path.length === 1 && Object.hasOwn(tokens.sharedColors, path[0])

// The themed colours of one theme, by output name. A theme that gives a
// shared colour its own value, or lacks a themed colour the dark theme has,
// stops the run: the outputs could not say it.
const themedColours = ({ theme, tokens }) => {
  const colours = leaves(tokens.themes[theme])
  colours
    .filter(([path]) => isShared({ path, tokens }))
    .forEach(([[key], value]) => {
      if (value !== tokens.sharedColors[key]) {
        throw new Error(
          `themes.${theme}.${key} is "${value}", but sharedColors.${key} ` +
            `is "${tokens.sharedColors[key]}": a shared colour has one value`
        )
      }
    })
  return colours
    .filter(([path]) => !isShared({ path, tokens }))
    .map(([path, value]) => ({ name: nameOf(path), value }))
    .sort(byName)
}

const themedByTheme = ({ tokens }) => {
  const dark = themedColours({ theme: 'dark', tokens })
  const light = themedColours({ theme: 'light', tokens })
  const names = (list) => list.map(({ name }) => name).join(',')
  if (names(dark) !== names(light)) {
    throw new Error(
      'themes.dark and themes.light name different themed colours'
    )
  }
  return { dark, light }
}

const sharedColours = ({ tokens }) =>
  leaves(tokens.sharedColors)
    .map(([path, value]) => ({ name: nameOf(path), value }))
    .sort(byName)

// A scale as [name, length] pairs.
const scale = ({ format, values }) =>
  Object.entries(values).map(([key, value]) => [kebab(key), format(value)])

// ---------------------------------------------------------------------------
// The web theme (theme.css)
// ---------------------------------------------------------------------------

const cssComment = (lines) => [
  `/* ${lines[0]}`,
  ...lines.slice(1).map((line) => ` * ${line}`),
  ' */'
]

const cssDeclaration = ([name, value]) => `  --${name}: ${value};`

const cssFamily = (family) =>
  /^[A-Za-z][\w-]*$/u.test(family) ? family : `'${family}'`

const fontStack = ({ key, tokens }) => {
  const loader = tokens.webFontVariable[key]
  return [
    ...(loader ? [`var(${loader})`] : []),
    cssFamily(tokens.fontFamily[key]),
    tokens.fontFallback
  ].join(', ')
}

// A token of the web theme, written as --<namespace>-<name>, or as
// --<namespace>-<name>--<modifier> for a property of that token, such as a
// font size's line height.
const inNamespace = ({ namespace, pairs }) =>
  pairs.map(([name, value]) => ({ name, namespace, value }))

const variableName = ({ modifier, name, namespace }) =>
  `${namespace}-${name}${modifier ? `--${modifier}` : ''}`

const cssToken = (token) =>
  cssDeclaration([variableName(token), token.value])

// The tokens of the web theme, per block and, inside a block, per group:
// @theme holds the colours, the font families, the shadows and the motion,
// @theme inline the scales. theme.css writes them and the theme names list
// them, so the two cannot name different tokens.
const webThemeTokens = ({ tokens }) => {
  const themed = themedByTheme({ tokens })
  const colours = inNamespace({
    namespace: 'color',
    pairs: [
      ...sharedColours({ tokens }).map(({ name, value }) => [name, value]),
      ...themed.dark.map(({ name }) => [name, `var(--c-${name})`])
    ].sort(([left], [right]) => compare(left, right))
  })
  const fonts = inNamespace({
    namespace: 'font',
    pairs: Object.keys(tokens.fontFamily).map((key) => [
      kebab(key),
      fontStack({ key, tokens })
    ])
  })
  const shadows = inNamespace({
    namespace: 'shadow',
    pairs: Object.entries(tokens.shadows).map(([key, value]) => [
      kebab(key),
      value
    ])
  })
  const motion = [
    ...inNamespace({
      namespace: 'duration',
      pairs: scale({ format: ms, values: tokens.motion.duration })
    }),
    ...inNamespace({
      namespace: 'ease',
      pairs: scale({ format: String, values: tokens.motion.easing })
    })
  ]
  const fontSizes = Object.entries(tokens.fontSize).flatMap(
    ([key, { lineHeight, size }]) => [
      { name: kebab(key), namespace: 'text', value: px(size) },
      {
        modifier: 'line-height',
        name: kebab(key),
        namespace: 'text',
        value: px(lineHeight)
      }
    ]
  )
  const scales = [
    ...inNamespace({
      namespace: 'spacing',
      pairs: [
        ...scale({ format: px, values: tokens.spacing }),
        ...scale({ format: px, values: tokens.inset })
      ]
    }),
    ...inNamespace({
      namespace: 'container',
      pairs: scale({ format: rem, values: tokens.layoutWidth })
    }),
    ...inNamespace({
      namespace: 'radius',
      pairs: scale({ format: px, values: tokens.radius })
    }),
    ...fontSizes,
    ...inNamespace({
      namespace: 'text',
      pairs: scale({ format: px, values: tokens.glyphSize })
    })
  ]

  return { inline: [scales], theme: [colours, fonts, shadows, motion] }
}

// The groups of one block, a blank line between two of them.
const cssGroups = (groups) =>
  groups.flatMap((group, index) => [
    ...(index === 0 ? [] : ['']),
    ...group.map(cssToken)
  ])

const renderWebTheme = ({ tokens }) => {
  const themed = themedByTheme({ tokens })
  const colourVar = ({ name, value }) => [`c-${name}`, value]
  const { inline, theme } = webThemeTokens({ tokens })

  return [
    ...cssComment(HEADER),
    '',
    ...cssComment([
      'The themed colours. The dark theme is the default; the light theme',
      "overrides it under [data-theme='light'], and every --color-* utility",
      'below reads them, so flipping data-theme on <html> repaints them all.'
    ]),
    ':root,',
    "[data-theme='dark'] {",
    ...themed.dark.map(colourVar).map(cssDeclaration),
    '}',
    '',
    "[data-theme='light'] {",
    ...themed.light.map(colourVar).map(cssDeclaration),
    '}',
    '',
    ...cssComment([
      'Every colour utility (a shared colour is a literal), the font',
      'families behind the variable next/font sets, the shadows and the',
      'motion. Utilities and hand-written rules read them through var().'
    ]),
    '@theme {',
    ...cssGroups(theme),
    '}',
    '',
    ...cssComment([
      'The scales, inlined into their utilities: p-lg is padding: 16px,',
      'max-w-content is max-width: 28rem.'
    ]),
    '@theme inline {',
    ...cssGroups(inline),
    '}',
    ''
  ].join('\n')
}

// ---------------------------------------------------------------------------
// The NativeWind preset (tailwind-preset.cjs)
// ---------------------------------------------------------------------------

const jsString = (value) =>
  `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const jsKey = (key) =>
  /^[A-Za-z_$][\w$]*$/u.test(key) ? key : jsString(key)

// A JS literal: objects one key per line, arrays and the objects inside
// them on one line.
const jsLiteral = ({ depth = 0, inline = false, value }) => {
  if (Array.isArray(value)) {
    return `[${value.map((item) => jsLiteral({ inline: true, value: item })).join(', ')}]`
  }
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value)
    if (inline) {
      return `{ ${entries.map(([key, child]) => `${jsKey(key)}: ${jsLiteral({ inline: true, value: child })}`).join(', ')} }`
    }
    const pad = '  '.repeat(depth + 1)
    const lines = entries.map(
      ([key, child]) =>
        `${pad}${jsKey(key)}: ${jsLiteral({ depth: depth + 1, value: child })}`
    )
    return `{\n${lines.join(',\n')}\n${'  '.repeat(depth)}}`
  }
  return typeof value === 'number' ? String(value) : jsString(value)
}

// The preset's colours, in the dark theme's shape: a themed colour reads its
// --c-* variable, which the mobile root view declares for the active theme
// (themeVars through NativeWind's vars()), and a shared colour is written as
// itself.
const presetColours = ({ tokens }) => {
  const visit = ({ path, value }) =>
    value !== null && typeof value === 'object'
      ? Object.fromEntries(
          Object.entries(value).map(([key, child]) => [
            kebab(key),
            visit({ path: [...path, key], value: child })
          ])
        )
      : isShared({ path, tokens })
        ? value
        : `var(--c-${nameOf(path)})`
  return visit({ path: [], value: tokens.themes.dark })
}

const renderNativewindPreset = ({ tokens }) => {
  const pairs = (list) => Object.fromEntries(list)
  const preset = {
    theme: {
      extend: {
        colors: presetColours({ tokens }),
        spacing: pairs([
          ...scale({ format: px, values: tokens.spacing }),
          ...scale({ format: px, values: tokens.inset })
        ]),
        maxWidth: pairs(
          scale({ format: rem, values: tokens.layoutWidth })
        ),
        borderRadius: pairs(scale({ format: px, values: tokens.radius })),
        fontFamily: pairs(
          Object.entries(tokens.fontFamily).map(([key, family]) => [
            kebab(key),
            [family, tokens.fontFallback]
          ])
        ),
        fontSize: pairs([
          ...Object.entries(tokens.fontSize).map(
            ([key, { lineHeight, size }]) => [
              kebab(key),
              [px(size), { lineHeight: px(lineHeight) }]
            ]
          ),
          ...scale({ format: px, values: tokens.glyphSize })
        ]),
        boxShadow: pairs(
          Object.entries(tokens.shadows).map(([key, value]) => [
            kebab(key),
            value
          ])
        )
      }
    }
  }

  return [
    ...HEADER.map((line) => `// ${line}`),
    '//',
    '// The NativeWind preset apps/mobile/tailwind.config.js loads. A themed',
    '// colour reads its --c-* variable, which the mobile root view declares',
    "// for the active theme (themeVars through NativeWind's vars()), so a class",
    '// follows the theme; a colour both themes share is written as itself. The',
    '// web reads theme.css instead and loads no JavaScript config.',
    '',
    "/** @type {import('tailwindcss').Config} */",
    `module.exports = ${jsLiteral({ value: preset })}`,
    ''
  ].join('\n')
}

// ---------------------------------------------------------------------------
// The mobile theme variables (src/themeVars.constant.ts)
// ---------------------------------------------------------------------------

const renderThemeVars = ({ tokens }) => {
  const themed = themedByTheme({ tokens })
  const entries = (theme) =>
    themed[theme]
      .map(({ name, value }) => `    '--c-${name}': ${jsString(value)}`)
      .join(',\n')

  return [
    ...HEADER.map((line) => `// ${line}`),
    '',
    "import type { ThemeEnumType } from '#src/tokens.constant'",
    '',
    '/**',
    ' * The --c-* variable of every themed colour, per theme: the map',
    " * NativeWind's vars() takes, so a class utility can read the active",
    ' * theme. A shared colour never changes with the theme and is not here.',
    ' */',
    'export const themeVars = {',
    '  dark: {',
    entries('dark'),
    '  },',
    '  light: {',
    entries('light'),
    '  }',
    // In Prettier's style: the package's ESLint run applies the prettier
    // rule to this file, .prettierignore or not.
    '} as const satisfies Record<ThemeEnumType, Record<`--c-${string}`, string>>',
    ''
  ].join('\n')
}

// ---------------------------------------------------------------------------
// The theme names (src/themeNames.constant.ts)
// ---------------------------------------------------------------------------

// A namespace of the web theme whose variables make no utility, so the
// theme names leave it out: tailwind-merge has nothing of it to merge.
// Tailwind 4 builds duration-* from --transition-duration-*, not from
// --duration-*, so --duration-shimmer makes no class; globals.css reads it
// through var().
const VARIABLE_ONLY_NAMESPACES = Object.freeze(['duration'])

// [namespace, names] for every namespace that makes a utility, both sorted.
const themeNamespaces = ({ tokens }) => {
  const { inline, theme } = webThemeTokens({ tokens })
  const named = [...theme, ...inline]
    .flat()
    .filter(
      ({ modifier, namespace }) =>
        !modifier && !VARIABLE_ONLY_NAMESPACES.includes(namespace)
    )
  const unique = (values) => [...new Set(values)].sort(compare)
  return unique(named.map(({ namespace }) => namespace)).map(
    (namespace) => [
      namespace,
      unique(
        named
          .filter((token) => token.namespace === namespace)
          .map(({ name }) => name)
      )
    ]
  )
}

// Prettier's width: the package's ESLint run applies the prettier rule to
// this output, .prettierignore or not.
const PRINT_WIDTH = 75

// One namespace as Prettier prints it: on one line when it fits, one name
// per line when it does not.
const tsNames = ({ last, names, namespace }) => {
  const comma = last ? '' : ','
  const line = `  ${namespace}: [${names.map(jsString).join(', ')}]${comma}`
  if (line.length <= PRINT_WIDTH) return [line]
  return [
    `  ${namespace}: [`,
    ...names.map(
      (name, index) =>
        `    ${jsString(name)}${index === names.length - 1 ? '' : ','}`
    ),
    `  ]${comma}`
  ]
}

const renderThemeNames = ({ tokens }) => {
  const namespaces = themeNamespaces({ tokens })

  return [
    ...HEADER.map((line) => `// ${line}`),
    '',
    '/**',
    ' * The name of every token utility the web theme declares, per Tailwind',
    ' * namespace: --spacing-pill-x is pill-x under spacing, the utility',
    ' * px-pill-x. A namespace whose variables make no utility, such as',
    " * --duration-*, is not here. Plain data: the web's shared tv registers",
    ' * it with tailwind-merge, so a new token merges with no code change.',
    ' */',
    'export const themeNames = {',
    ...namespaces.flatMap(([namespace, names], index) =>
      tsNames({ last: index === namespaces.length - 1, names, namespace })
    ),
    '} as const satisfies Record<string, readonly string[]>',
    ''
  ].join('\n')
}

// ---------------------------------------------------------------------------
// Every output
// ---------------------------------------------------------------------------

const RENDERERS = Object.freeze({
  nativewindPreset: renderNativewindPreset,
  themeNames: renderThemeNames,
  themeVars: renderThemeVars,
  webTheme: renderWebTheme
})

export const renderOutputs = ({ tokens }) =>
  Object.entries(OUTPUTS).map(([id, path]) => ({
    content: RENDERERS[id]({ tokens }),
    path
  }))

// Line endings aside: with core.autocrlf a Windows checkout holds the files
// as CRLF, and an unchanged output is left alone.
const writeIfChanged = ({ content, target }) => {
  const current = existsSync(target)
    ? readFileSync(target, 'utf8').replace(/\r\n/gu, '\n')
    : null
  if (current === content) return false
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, content)
  return true
}

const main = () => {
  const { values } = parseArgs({
    options: { 'package-dir': { default: PACKAGE_DIR, type: 'string' } }
  })
  const packageDir = resolve(values['package-dir'])
  const outputs = renderOutputs({ tokens: loadTokens({ packageDir }) })
  const written = outputs.filter(({ content, path }) =>
    writeIfChanged({ content, target: join(packageDir, path) })
  )
  process.stdout.write(
    `generate: ${outputs.length} output(s) from ${SOURCE}, ` +
      `${written.length} written\n` +
      written.map(({ path }) => `  ${path}\n`).join('')
  )
}

