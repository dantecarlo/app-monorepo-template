import '@/app/globals.css'

import { APP_NAME, DEFAULT_LANGUAGE } from '@app/i18n'
import { DEFAULT_THEME } from '@app/tokens'
import type { Metadata, Viewport } from 'next'
import localFont from 'next/font/local'
import { Suspense } from 'react'

import { LocaleProviders } from '@/app/LocaleProviders'
import { ThemeProvider } from '@/components/ThemeProvider'
import { NO_FLASH_LOCALE_SCRIPT } from '@/i18n/noFlashLocale.constant'
import { NO_FLASH_THEME_SCRIPT } from '@/lib/theme/noFlashTheme.constant'

// Self-hosted, so the build never fetches a font. The files in ./fonts are the
// Latin variable woff2 files Google Fonts serves, one per family with its OFL
// licence; docs/architecture/web.md § 4 says how to update them.
const montserrat = localFont({
  display: 'swap',
  src: './fonts/montserrat-latin.woff2',
  variable: '--font-montserrat',
  weight: '400 800'
})

const inter = localFont({
  display: 'swap',
  src: './fonts/inter-latin.woff2',
  variable: '--font-inter',
  weight: '400 500'
})

export const metadata: Metadata = {
  description:
    'A production-grade Next.js starter with fractal architecture, glass design system, TanStack Query, and Zustand.',
  // metadataBase is required for fully-qualified Open Graph / Twitter URLs.
  // Point at the real production URL via an env var in deployed environments.
  metadataBase: new URL('http://localhost:3000'),
  title: {
    default: APP_NAME,
    template: `%s · ${APP_NAME}`
  }
}

// Exported separately from `metadata` per Next 16 convention.
// 'dark light' lets the UA render form controls / scrollbars for whichever
// theme the user resolved to via cookie or prefers-color-scheme.
export const viewport: Viewport = {
  colorScheme: 'dark light'
}

// ---------------------------------------------------------------------------
// Layout props — typed via the LayoutProps helper generated by `next typegen`.
// Convention: use LayoutProps<'/route'> for layouts; PageProps<'/route'> for
// pages. Generated types live in .next/types after running `next typegen`
// (which the `typecheck` script runs automatically before `tsc --noEmit`).
// ---------------------------------------------------------------------------
interface IRootLayoutProps {
  children: React.ReactNode
}

// The document shell is static: it writes the default language and theme,
// which the pre-paint scripts replace with the cookie's choices, and renders
// the providers inside <Suspense>, where LocaleProviders reads the request's
// locale. Reading it outside <Suspense> would block every route.
const RootLayout = ({ children }: IRootLayoutProps) => (
  <html
    className={`${montserrat.variable} ${inter.variable}`}
    data-theme={DEFAULT_THEME}
    lang={DEFAULT_LANGUAGE}
    suppressHydrationWarning
  >
    <head>
      {/* Blocking pre-paint scripts: the theme's resolves data-theme from the
          NEXT_THEME cookie, else prefers-color-scheme, and the locale's sets
          lang from the NEXT_LOCALE cookie, both before first paint and over
          the static defaults above. */}
      <script
        dangerouslySetInnerHTML={{ __html: NO_FLASH_THEME_SCRIPT }}
      />
      <script
        dangerouslySetInnerHTML={{ __html: NO_FLASH_LOCALE_SCRIPT }}
      />
    </head>
    <body className="min-h-screen">
      <ThemeProvider>
        <Suspense>
          <LocaleProviders>{children}</LocaleProviders>
        </Suspense>
      </ThemeProvider>
    </body>
  </html>
)

export default RootLayout
